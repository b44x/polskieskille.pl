#!/usr/bin/env python3
"""Build static Polish skill pages and sitemap for GitHub Pages; stdlib only."""

import argparse
import html
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
SITE = "https://polskieskille.pl"
REPO = "https://github.com/b44x/ai-polish-skills"
CATEGORY = {"finance": "Finanse", "legal": "Prawo i rejestry", "public_data": "Dane publiczne", "utilities": "Na co dzień", "logistics": "Logistyka", "entertainment": "Filmy i seriale", "health": "Zdrowie", "e-commerce": "Zakupy", "general": "Praca i inne"}
SOURCE = {"official_api": ("Oficjalne API", "official"), "public_api": ("Publiczne API", "public"), "unofficial_api": ("Nieoficjalne API", "unofficial"), "scraping": ("Dane ze strony", "unofficial"), "static_data": ("Obliczenia lokalne", "public")}
SIGNATURE = "<!-- Generated by scripts/build_seo.py; edit content/skills.json instead. -->"


def esc(value):
    return html.escape(str(value), quote=True)


def load_copy(root=ROOT):
    return json.loads((root / "content/skills.json").read_text(encoding="utf-8"))


def skill_url(slug):
    return SITE + "/skille/" + slug + "/"


def json_ld(value):
    # Escaping '<' keeps embedded data from terminating its script element.
    return json.dumps(value, ensure_ascii=False, separators=(",", ":")).replace("<", "\\u003c")


def catalogue_html(registry, copy):
    """Cards for the homepage's existing #grid; markup also works without JS."""
    cards = []
    for skill in registry["skills"]:
        slug, command = skill["name"], skill["install"]["curl"]
        words = copy[slug]
        label, badge = SOURCE[skill["source_type"]]
        asks = "".join('<div class="ask">{}</div>'.format(esc(p)) for p in words["prompts"][:2])
        cards.append('''<article class="card">
<div class="top"><div><h3><a href="/skille/{slug}/">{name}</a></h3><div class="slug">{slug} · v{version}</div></div><span class="badge {badge}">{label}</span></div>
<p class="meta">{description}</p><div class="meta">{category} · {source}</div>
<div class="asks">{asks}</div>
<div class="foot"><code>{command}</code><button class="copy" data-text="{command}" aria-label="Kopiuj instalację: {name}">Kopiuj</button></div>
<div class="links"><a href="/skille/{slug}/">Opis i przykłady</a><a href="{repo}/blob/main/skills/{slug}/SKILL.md">SKILL.md</a></div>
</article>'''.format(slug=esc(slug), name=esc(skill["display_name"]), version=esc(skill["version"]), badge=badge, label=label,
                      description=esc(words["description"]), category=esc(CATEGORY[skill["category"]]), source=esc(skill["source"]),
                      asks=asks, command=esc(command), repo=REPO))
    return "\n".join(cards)


def home_schema(registry, copy=None):
    """Structured homepage catalogue; no fabricated ratings or commercial offers."""
    copy = load_copy() if copy is None else copy
    items = [{"@type": "ListItem", "position": i, "item": {"@type": "WebPage", "@id": skill_url(s["name"]),
              "url": skill_url(s["name"]), "name": copy[s["name"]]["h1"]}}
             for i, s in enumerate(registry["skills"], 1)]
    return {"@context": "https://schema.org", "@graph": [
        {"@type": "WebSite", "@id": SITE + "/#website", "url": SITE + "/", "name": "Polskie Skille", "inLanguage": "pl"},
        {"@type": "CollectionPage", "@id": SITE + "/#catalogue", "url": SITE + "/", "name": "Polskie skille dla agentów AI",
         "inLanguage": "pl", "isPartOf": {"@id": SITE + "/#website"},
         "mainEntity": {"@type": "ItemList", "numberOfItems": len(items), "itemListElement": items}}
    ]}


def page_schema(skill, words):
    url = skill_url(skill["name"])
    return {"@context": "https://schema.org", "@graph": [
        {"@type": "SoftwareSourceCode", "@id": url + "#skill", "name": words["h1"], "description": words["description"],
         "url": url, "mainEntityOfPage": url, "codeRepository": REPO + "/tree/main/skills/" + skill["name"],
         "programmingLanguage": "Python", "runtimePlatform": "Python 3.8+", "inLanguage": "pl",
         "version": skill["version"], "license": REPO + "/blob/main/LICENSE", "isAccessibleForFree": True},
        {"@type": "BreadcrumbList", "itemListElement": [
            {"@type": "ListItem", "position": 1, "name": "Polskie Skille", "item": SITE + "/"},
            {"@type": "ListItem", "position": 2, "name": words["h1"], "item": url}]}
    ]}


def render_home(current, registry, copy):
    """Refresh generated regions while preserving the hand-written landing page."""
    def region(text, name, body):
        pattern = r"(<!-- " + re.escape(name) + r":START -->).*?(<!-- " + re.escape(name) + r":END -->)"
        text, count = re.subn(pattern, lambda match: match.group(1) + "\n" + body + "\n" + match.group(2), text, flags=re.DOTALL)
        if count != 1:
            raise ValueError("Expected exactly one homepage region: " + name)
        return text

    data = dict(registry)
    data["skills"] = [dict(skill, site_description=copy[skill["name"]]["description"],
                           site_prompts=copy[skill["name"]]["prompts"][:3]) for skill in registry["skills"]]
    current = region(current, "CATALOG", catalogue_html(registry, copy))
    current = region(current, "HOME-SCHEMA", '<script type="application/ld+json">' + json_ld(home_schema(registry, copy)) + '</script>')
    current = region(current, "CATALOG-DATA", '<script type="application/json" id="catalog-data">' + json_ld(data) + '</script>')
    current = re.sub(r'(<span id="count">)[^<]*(</span>)', lambda m: m.group(1) + str(len(data["skills"])) + m.group(2), current)
    current = re.sub(r'(<p class="catalog-status" id="catalog-status"[^>]*>)[^<]*(</p>)',
                     lambda m: m.group(1) + "Dostępne skille: " + str(len(data["skills"])) + "." + m.group(2), current)
    return current


def list_html(items):
    return "\n".join("<li>{}</li>".format(esc(item)) for item in items)


