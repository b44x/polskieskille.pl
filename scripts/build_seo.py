def build(check=False, root=ROOT):
    registry = json.loads((root / "assets/registry.min.json").read_text(encoding="utf-8"))
    copy = load_copy(root)
    skills = {s["name"]: s for s in registry["skills"]}
    if len(skills) != len(registry["skills"]) or set(copy) != set(skills):
        raise ValueError("Registry and content/skills.json must contain the same unique skill names")
    pages = {root / "index.html": render_home((root / "index.html").read_text(encoding="utf-8"), registry, copy)}
    for slug, skill in skills.items():
        if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", slug):
            raise ValueError("Invalid skill slug")
        words = copy[slug]
        for name in words["related"]:
            if name not in skills or name == slug:
                raise ValueError("Invalid related skill: " + name)
        pages[root / "skille" / slug / "index.html"] = render_page(skill, words, skills, copy)
    urls = [SITE + "/"] + [skill_url(slug) for slug in sorted(skills)]
    pages[root / "sitemap.xml"] = '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' + "\n".join("  <url><loc>{}</loc></url>".format(esc(url)) for url in urls) + "\n</urlset>\n"
    stale = []
    for path, body in pages.items():
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != body:
                stale.append(str(path.relative_to(root)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(body, encoding="utf-8")
    if stale:
        print("Outdated SEO artifacts: " + ", ".join(stale), file=sys.stderr)
        return 1
    print("{} homepage, {} skill pages and sitemap".format("Checked" if check else "Built", len(skills)))
    return 0


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if generated pages or sitemap differ; do not write files")
    args = parser.parse_args()
    try:
        sys.exit(build(check=args.check))
    except (OSError, ValueError, KeyError) as exc:
        print("SEO build failed: " + str(exc), file=sys.stderr)
        sys.exit(1)
